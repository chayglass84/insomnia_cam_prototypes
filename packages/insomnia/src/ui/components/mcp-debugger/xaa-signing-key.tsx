import React, { type FC, useState } from 'react';
import { Button, Tooltip, TooltipTrigger } from 'react-aria-components';

import type { AssertionAlg, AssertionAudience, ClientKeyInfo } from '~/main/mcp-debugger/client-assertion';

import { JsonView } from './json-view';
import { smallButton, tooltipClass } from './oauth-discovery-panel';
import { SegmentedToggle } from './segmented-toggle';

// Task 4348 S9a: the signing key for client assertions (private_key_jwt), inside the XAA wizard. Generate one (the private
// half stays in the main process; only the public JWKS comes here to copy and register), or paste a private key you
// already registered at your IdP. The assertion's audience is a toggle because servers disagree about it.
// PROTOTYPE-MOCK: one key per request, used at both servers; kept in memory only; the mock helper registers the public key
// with the local mock servers' admin endpoints so the flow can be tried without an IdP console.

export const SigningKeyPanel: FC<{
  requestId: string;
  keyInfo: ClientKeyInfo | null;
  onKeyChange: (key: ClientKeyInfo | null) => void;
  audience: AssertionAudience;
  onAudienceChange: (audience: AssertionAudience) => void;
  /** Where the mock servers' admin endpoints are, when the wizard is pointed at local mocks (shows the register helper). */
  mockTargets?: { idpIssuer: string; idpClientId: string; asIssuer?: string; asClientId: string };
}> = ({ requestId, keyInfo, onKeyChange, audience, onAudienceChange, mockTargets }) => {
  const [pasting, setPasting] = useState(false);
  const [pem, setPem] = useState('');
  const [kid, setKid] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [registered, setRegistered] = useState<string | null>(null);

  const run = async (work: () => Promise<ClientKeyInfo>) => {
    setError(null);
    setRegistered(null);
    try {
      onKeyChange(await work());
      setPasting(false);
      setPem('');
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
    }
  };
  const generate = (alg: AssertionAlg) => run(() => window.main.mcpDebugger.xaaGenerateKey({ requestId, alg }));
  const useThisKey = () => run(() => window.main.mcpDebugger.xaaImportKey({ requestId, pem, kid: kid.trim() || undefined }));
  const replace = async () => {
    await window.main.mcpDebugger.xaaClearKey({ requestId });
    onKeyChange(null);
    setRegistered(null);
  };

  // A plain text/plain POST is a "simple" request, so no CORS preflight is needed; the mocks answer with the CORS header.
  const registerWithMocks = async () => {
    if (!keyInfo || !mockTargets) {
      return;
    }
    setError(null);
    try {
      const post = (base: string, clientId: string) => fetch(`${base.replace(/\/+$/, '')}/admin/clients`, { method: 'POST', body: JSON.stringify({ clientId, jwks: keyInfo.jwks }) });
      const responses = [await post(mockTargets.idpIssuer, mockTargets.idpClientId)];
      if (mockTargets.asIssuer) {
        responses.push(await post(mockTargets.asIssuer, mockTargets.asClientId));
      }
      setRegistered(responses.every(r => r.ok) ? `Registered at ${responses.length === 1 ? 'the mock IdP' : 'the mock IdP and the mock authorization server'}.` : 'A mock server refused the registration (check the client id).');
    } catch (err) {
      setError(`Could not reach the mock servers: ${err instanceof Error ? err.message : String(err)}`);
    }
  };

  return (
    <div className="flex flex-col gap-2 rounded-xs border border-solid border-(--hl-md) p-2" data-testid="mcp-xaa-key-panel">
      <div className="flex items-center gap-2 text-xs">
        <span className="font-semibold">Signing key</span>
        <span className="text-(--hl)">Insomnia signs a short-lived assertion with it instead of sending a secret.</span>
      </div>
      {error && (
        <p className="text-xs text-red-500 [overflow-wrap:anywhere]" data-testid="mcp-xaa-key-error">
          {error}
        </p>
      )}
      {keyInfo ? (
        <>
          <div className="flex flex-wrap items-center gap-2 text-xs" data-testid="mcp-xaa-key-info">
            <span className="rounded-xs border border-solid border-(--hl-md) px-1.5 py-0.5 font-mono">{keyInfo.alg}</span>
            <span className="text-(--hl)">kid</span>
            <code className="min-w-0 break-all select-all">{keyInfo.kid}</code>
            <span className="text-(--hl)">{keyInfo.generated ? 'generated by Insomnia' : 'pasted'}</span>
            <Button className={`${smallButton} ml-auto`} onPress={replace} data-testid="mcp-xaa-key-replace">
              Replace key
            </Button>
          </div>
          <p className="text-xs text-(--hl)">Register this public key (a JWKS) at your identity provider and at the MCP authorization server.</p>
          <JsonView value={keyInfo.jwks} />
          {mockTargets && (
            <div className="flex flex-wrap items-center gap-2">
              <Button className={smallButton} onPress={registerWithMocks} data-testid="mcp-xaa-key-register-mocks">
                Register with the mock servers
              </Button>
              <span className="text-xs text-(--hl)">Prototype mock: calls the local mocks&apos; admin endpoints, like pasting the JWKS into an IdP console.</span>
              {registered && (
                <span className="text-xs text-green-500" data-testid="mcp-xaa-key-registered">
                  {registered}
                </span>
              )}
            </div>
          )}
          <div className="flex items-center gap-2 text-xs">
            <span className="text-(--hl)">Assertion audience</span>
            <TooltipTrigger delay={200}>
              <SegmentedToggle
                label="Assertion audience"
                testIdPrefix="mcp-xaa-audience"
                value={audience}
                onChange={onAudienceChange}
                options={[
                  { id: 'token-endpoint', label: 'Token endpoint' },
                  { id: 'issuer', label: 'Issuer' },
                ]}
              />
              <Tooltip offset={8} className={tooltipClass}>
                What the assertion&apos;s aud names. Servers disagree: most want the token endpoint URL, some want the issuer. If a server
                answers invalid_client, try the other one.
              </Tooltip>
            </TooltipTrigger>
          </div>
        </>
      ) : (
        <>
          <div className="flex flex-wrap items-center gap-2">
            <Button className={smallButton} onPress={() => generate('RS256')} data-testid="mcp-xaa-key-generate-rsa">
              Generate a key (RS256)
            </Button>
            <Button className={smallButton} onPress={() => generate('ES256')} data-testid="mcp-xaa-key-generate-ec">
              Generate a key (ES256)
            </Button>
            <Button className={smallButton} onPress={() => setPasting(open => !open)} data-testid="mcp-xaa-key-paste">
              Paste a private key
            </Button>
          </div>
          {pasting && (
            <div className="flex flex-col gap-2">
              <textarea
                aria-label="Private key (PEM)"
                className="h-28 w-full rounded-xs border border-solid border-(--hl-md) bg-transparent p-2 font-mono text-xs"
                placeholder={'-----BEGIN PRIVATE KEY-----\n…\n-----END PRIVATE KEY-----'}
                value={pem}
                spellCheck={false}
                onChange={event => setPem(event.target.value)}
                data-testid="mcp-xaa-key-pem"
              />
              <div className="flex items-center gap-2">
                <input
                  aria-label="Key ID (kid)"
                  className="w-64 rounded-xs border border-solid border-(--hl-md) bg-transparent px-2 py-1 text-xs"
                  placeholder="kid it is registered under (optional)"
                  value={kid}
                  onChange={event => setKid(event.target.value)}
                  data-testid="mcp-xaa-key-kid"
                />
                <Button className={smallButton} onPress={useThisKey} isDisabled={pem.trim() === ''} data-testid="mcp-xaa-key-use">
                  Use this key
                </Button>
                <span className="text-xs text-(--hl)">RSA or EC P-256, unencrypted. It stays in Insomnia&apos;s main process and is never saved.</span>
              </div>
            </div>
          )}
        </>
      )}
    </div>
  );
};
